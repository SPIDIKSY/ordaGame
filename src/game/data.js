export function weaponFacts(id, l, p) {
  const I = WINFO[id], F = WFACT[id] || {}, A = p.amount || 0, out = [];
  const hit = Math.round(p.dmg * I.hit(l) * topK(l)), cd = I.cd ? I.cd(l) * (p.cdMul || 1) : 0, n = F.n ? F.n(l, A) : 0;
  const cnt = n ? n + ' ' + plural(n, F.w) : '';
  if (I.tick) {
    out.push(hit + ' урона каждые ' + n2(I.tick) + ' с');
    if (cd) out.push(cnt + ' раз в ' + n2(cd) + ' с');
  } else if (F.touch) out.push(hit + ' урона за касание', cnt);
  else {
    out.push((F.range ? '0–' : '') + hit + ' ' + (F.label || 'урона за удар'));
    out.push((F.hits ? 'бьёт ' + cnt : cnt) + (cnt ? ' ' : '') + 'раз в ' + n2(cd) + ' с');
  }
  if (F.tag) out.push(F.tag);
  return out.join(' · ');
}
