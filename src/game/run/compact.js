/* =====================================================
   УБОРКА СПИСКОВ БЕЗ МУСОРА
   Каждый кадр из списков забега убирается отработавшее:
   мёртвые враги, погасшие снаряды, растаявшие частицы.
   Раньше это делалось через filter — он создаёт новый
   массив, и так 15 раз за кадр. Браузер копит эти массивы
   и время от времени замирает, чтобы их убрать, — отсюда
   рывки. Здесь список чистится на месте, порядок сохраняется.
   ===================================================== */
export function compact(list, keep) {
  let j = 0;
  for (let i = 0; i < list.length; i++) { const q = list[i]; if (keep(q)) list[j++] = q; }
  list.length = j;
}

// Условия заведены один раз: стрелка, написанная прямо в вызове,
// тоже создавалась бы заново на каждом кадре
export const alive = (q) => q.life > 0;
export const notTaken = (q) => !q.take;
export const notDead = (e) => !e.dead;
export const notDone = (q) => !q.done;
export const corpseVisible = (q) => q.t < q.life;
export const ringVisible = (q) => q.age < q.life;
